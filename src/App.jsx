import { useState } from "react";
import ErrorMessage from "./components/ErrorMessage.jsx";
import Loading from "./components/Loading.jsx";
import OrderForm from "./components/OrderForm.jsx";
import PredictionResult from "./components/PredictionResult.jsx";
import { predictOrder } from "./services/api.js";
import "./dashboard.css";

function App() {
  const [prediction, setPrediction] = useState(null);
  const [submittedOrder, setSubmittedOrder] = useState(null);
  const [error, setError] = useState("");
  const [isLoading, setIsLoading] = useState(false);

  async function handlePredict(order) {
    setSubmittedOrder(order);
    setIsLoading(true);
    setError("");
    setPrediction(null);

    try {
      setPrediction(await predictOrder(order));
    } catch (requestError) {
      setError(requestError.message || "Unable to get a prediction right now.");
    } finally {
      setIsLoading(false);
    }
  }

  return (
    <div className="app-shell">
      <header className="topbar">
        <a className="brand" href="#main" aria-label="Returnwise home">
          <span className="brand-mark" aria-hidden="true">
            <span />
            <span />
            <span />
          </span>
          <span>returnwise</span>
        </a>
        <div className="topbar-meta">
          <span className="service-indicator" aria-hidden="true" />
          <span>Order intelligence</span>
          <span className="meta-divider" />
          <span className="model-tag">MODEL 01</span>
        </div>
      </header>

      <main id="main" className="workspace">
        <section className="page-heading" aria-labelledby="page-title">
          <div>
            <p className="eyebrow">
              PREDICTION WORKSPACE <span>/</span> RETURNS
            </p>
            <h1 id="page-title">Order return assessment</h1>
            <p className="page-description">
              Estimate return likelihood from order and customer details.
            </p>
          </div>
          <div className="backend-badge">
            <span className="backend-mark" aria-hidden="true">
              AI
            </span>
            <span>
              Powered by <strong>Order Return Model</strong>
            </span>
          </div>
        </section>

        <div className="workspace-grid">
          <section className="form-panel" aria-labelledby="form-title">
            <div className="section-heading">
              <div>
                <p className="section-kicker">INPUT</p>
                <h2 id="form-title">Order profile</h2>
              </div>
              <span className="required-note">
                <span>*</span> Required
              </span>
            </div>
            <OrderForm onSubmit={handlePredict} isLoading={isLoading} />
          </section>

          <aside
            className="result-panel"
            aria-labelledby="result-title"
            aria-live="polite"
          >
            <div className="result-panel-heading">
              <div>
                <p className="section-kicker">MODEL OUTPUT</p>
                <h2 id="result-title">Prediction</h2>
              </div>
              <span className="result-index">01</span>
            </div>

            {isLoading && <Loading />}
            {error && <ErrorMessage message={error} />}
            {prediction && !isLoading && (
              <PredictionResult result={prediction} order={submittedOrder} />
            )}
            {!prediction && !isLoading && !error && (
              <div className="empty-result">
                <div className="empty-visual" aria-hidden="true">
                  <div className="visual-ring visual-ring-outer" />
                  <div className="visual-ring visual-ring-inner" />
                  <span className="visual-center" />
                  <span className="visual-point visual-point-one" />
                  <span className="visual-point visual-point-two" />
                  <span className="visual-point visual-point-three" />
                </div>
                <p className="empty-title">Your result will appear here</p>
                <p className="empty-copy">
                  Complete the order profile and run a prediction to see the
                  model assessment.
                </p>
                <div className="empty-divider" />
                <div className="empty-footnote">
                  <span className="footnote-symbol" aria-hidden="true">
                    i
                  </span>
                  <span>
                    Predictions are generated by the connected AI model.
                  </span>
                </div>
              </div>
            )}
          </aside>
        </div>

        <footer className="page-footer">
          <span>
            RETURNWISE <span className="footer-dot">·</span> ORDER ANALYTICS
          </span>
          <span>Predictions are estimates, not guarantees.</span>
        </footer>
      </main>
    </div>
  );
}

export default App;
